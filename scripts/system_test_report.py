"""
Generate docs/test-results/SYSTEM_TEST_REPORT.md.

Runs every automated test module that backs a system-level (ST-*) test
case from the Test Case Catalogue / Test Plan Appendix A.3, records the
real result of each run, and writes a report mapping each ST case to its
requirement, its evidence module and that module's actual result.

Usage (repo root, virtualenv active):
    python scripts/system_test_report.py
"""
import os
import re
import subprocess
import sys
from datetime import datetime

# (ID, requirement, description, test label or None if manual)
CASES = [
    ("ST-AUTH-01", "BBMS-F-001", "End-to-end valid login workflow", "authentication.tests.test_login"),
    ("ST-AUTH-02", "BBMS-F-002", "End-to-end logout workflow", "authentication.tests.test_logout"),
    ("ST-DONOR-01", "BBMS-F-003", "End-to-end new donor registration workflow", "donors.tests"),
    ("ST-DNTN-01", "BBMS-F-007", "End-to-end donation recording workflow", "donations.tests"),
    ("ST-DNTN-02", "BBMS-F-008", "Donor views own donation history", "donations.tests"),
    ("ST-BG-01", "BBMS-F-010", "Selected blood group consistent across workflow", "requests.test_end_to_end"),
    ("ST-BG-02", "BBMS-F-010", "All blood groups listed, including zero-stock groups", "inventory.tests"),
    ("ST-INV-01", "BBMS-F-011", "Staff review of inventory summary", "inventory.tests"),
    ("ST-INV-02", "BBMS-F-022", "Expiry information recorded for a stored unit", "inventory.tests"),
    ("ST-SRCH-01", "BBMS-F-012", "End-to-end availability search", "inventory.tests"),
    ("ST-SRCH-02", "BBMS-F-012", "Unauthenticated users cannot access availability search", "inventory.tests_access"),
    ("ST-REQ-01", "BBMS-F-014", "Request submission and status tracking", "requests.tests"),
    ("ST-REQ-02", "BBMS-F-016", "Request exceeding stock flagged for staff review", "requests.tests"),
    ("ST-ISS-01", "BBMS-F-017", "End-to-end approve-and-issue workflow", "requests.tests"),
    ("ST-ISS-02", "BBMS-F-016", "Rejected request cannot proceed to issue", "requests.tests"),
    ("ST-ADM-01", "BBMS-F-020", "End-to-end user account management workflow", "accounts.tests"),
    ("ST-ADM-02", "BBMS-F-020", "Non-administrator cannot access user management", "accounts.tests"),
    ("ST-INT-01", "BBMS-F-006/007/009/014/016/017/018",
     "Full donor > eligibility > donation > inventory > request > approval > issue > audit",
     "requests.test_end_to_end"),
    ("ST-COMPAT-01", "BBMS-NF-006", "Browser/device compatibility walkthrough", None),
]


def git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True).stdout.strip()


def run_label(label):
    proc = subprocess.run(
        [sys.executable, "manage.py", "test", label, "--noinput", "-v", "2"],
        capture_output=True, text=True,
    )
    out = proc.stdout + proc.stderr
    ran = re.search(r"^Ran (\d+) tests? in ([\d.]+)s", out, re.M)
    names = re.findall(r"^(test_\w+) \(([\w.]+)\)", out, re.M)
    return {
        "ok": proc.returncode == 0,
        "ran": int(ran.group(1)) if ran else 0,
        "secs": ran.group(2) if ran else "?",
        "names": names,
    }


def main():
    os.environ.setdefault("DJANGO_SECRET_KEY", "system-test-report-throwaway-key")
    os.environ.setdefault("DJANGO_DEBUG", "True")

    labels = sorted({c[3] for c in CASES if c[3]})
    results = {}
    for label in labels:
        print(f"Running {label} ...", flush=True)
        results[label] = run_label(label)
        r = results[label]
        print(f"  {'PASS' if r['ok'] else 'FAIL'} - {r['ran']} tests in {r['secs']}s")

    auto = [c for c in CASES if c[3]]
    passed = sum(1 for c in auto if results[c[3]]["ok"])
    manual = len(CASES) - len(auto)
    all_ok = all(r["ok"] for r in results.values())

    lines = [
        "# BBMS System Test Report",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Run at | {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} |",
        f"| Run by | {git('config', 'user.name')} |",
        f"| Commit tested | `{git('rev-parse', '--short', 'HEAD')}` (branch `{git('rev-parse', '--abbrev-ref', 'HEAD')}`) |",
        f"| Python | {sys.version.split()[0]} |",
        "| Database | SQLite test database (created and destroyed by Django per run) |",
        "| Generated by | `scripts/system_test_report.py` |",
        "",
        "## Summary",
        "",
        f"- System test cases: **{len(CASES)}** (Test Plan v2.1 Appendix A.3)",
        f"- Automated: **{len(auto)}**, of which **{passed} passed** and {len(auto) - passed} failed",
        f"- Not executed (manual verification required): **{manual}**",
        f"- Overall automated result: **{'PASS' if all_ok else 'FAIL'}**",
        "",
        "Each result below is the real exit status of `python manage.py test <module>`",
        "for the module that implements that system test case. Nothing is estimated.",
        "",
        "## Results by test case",
        "",
        "| ID | Requirement | Scenario | Evidence (test module) | Result |",
        "| --- | --- | --- | --- | --- |",
    ]
    for cid, req, desc, label in CASES:
        if label:
            res = "Pass" if results[label]["ok"] else "**FAIL**"
            lines.append(f"| {cid} | {req} | {desc} | `{label}` | {res} |")
        else:
            lines.append(f"| {cid} | {req} | {desc} | Manual walkthrough (no browser automation) | Not executed |")

    lines += [
        "",
        "## Test module runs",
        "",
        "| Module | Tests run | Time | Result |",
        "| --- | --- | --- | --- |",
    ]
    for label in labels:
        r = results[label]
        lines.append(f"| `{label}` | {r['ran']} | {r['secs']}s | {'OK' if r['ok'] else 'FAILED'} |")

    e2e = results.get("requests.test_end_to_end")
    if e2e:
        lines += [
            "",
            "## ST-INT-01: full workflow test",
            "",
            "`requests/test_end_to_end.py` drives the whole system through the web",
            "layer in one test: donor registration, eligibility, donation recording,",
            "automatic inventory credit, an anonymous blood request, staff approval,",
            "issue with automatic inventory debit, and the resulting audit trail.",
            "",
            "Tests executed:",
            "",
        ]
        lines += [f"- `{full}`" for _name, full in e2e["names"]]

    lines += [
        "",
        "## Not executed",
        "",
        "- **ST-COMPAT-01** (BBMS-NF-006): needs a manual walkthrough of login, search,",
        "  request and issue in Chrome, Firefox and Safari. No browser-automation tool",
        "  is used in this project, so this case is not marked as passed.",
        "",
    ]

    os.makedirs("docs/test-results", exist_ok=True)
    path = "docs/test-results/SYSTEM_TEST_REPORT.md"
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print(f"\nReport written to {path}")
    sys.exit(0 if all_ok else 1)


if __name__ == "__main__":
    main()
