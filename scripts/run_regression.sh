#!/usr/bin/env bash
# BBMS regression run (Test Plan v2.0, Section 15).
#
# Runs every verification check from the Test Plan against a clean,
# throwaway copy of the currently committed code (git HEAD), so the
# developer's own db.sqlite3 and working-tree edits are never touched.
# Writes a dated Markdown report with the real command output to
# docs/regression/REGRESSION_RUN_<YYYY-MM-DD>.md.
#
# Usage (from the repository root, with your virtualenv active):
#   bash scripts/run_regression.sh
#
# Exit code: 0 if every check passed, 1 otherwise.

set -u

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

PY="${PYTHON:-python}"
RUN_DATE="$(date +%Y-%m-%d)"
RUN_TIME="$(date '+%Y-%m-%d %H:%M:%S %Z')"
COMMIT="$(git rev-parse --short HEAD)"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"
RUNNER="$(git config user.name) <$(git config user.email)>"

REPORT_DIR="$REPO_ROOT/docs/regression"
REPORT="$REPORT_DIR/REGRESSION_RUN_${RUN_DATE}.md"
mkdir -p "$REPORT_DIR"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
git archive HEAD | tar -x -C "$WORK"

export DJANGO_SECRET_KEY="regression-run-throwaway-key-not-for-deployment"
export DJANGO_DEBUG="True"

FAILED=0
SUMMARY_ROWS=""

# run_check <id> <description> <command...>
run_check() {
    local id="$1" desc="$2"; shift 2
    local out rc start end secs status
    start=$(date +%s)
    out="$(cd "$WORK" && "$@" 2>&1)"; rc=$?
    end=$(date +%s); secs=$((end - start))
    if [ $rc -eq 0 ]; then status="PASS"; else status="FAIL"; FAILED=1; fi
    SUMMARY_ROWS="${SUMMARY_ROWS}| ${id} | ${desc} | \`$*\` | ${status} | ${secs}s |
"
    {
        echo "### ${id} — ${desc}"
        echo
        echo "Command: \`$*\`  "
        echo "Exit code: ${rc} — **${status}** (${secs}s)"
        echo
        echo '```'
        # Keep the report readable: the summary lines are at the end of
        # Django's output, so keep the last 40 lines of each command.
        echo "$out" | tail -n 40
        echo '```'
        echo
    } >> "$WORK/.details.md"
    echo "[$status] $id $desc (${secs}s)"
}

echo "BBMS regression run — commit $COMMIT on $BRANCH"
echo

run_check "REG-01" "Django system check" \
    "$PY" manage.py check
run_check "REG-02" "Migration drift check" \
    "$PY" manage.py makemigrations --check --dry-run
run_check "REG-03" "Fresh-database migration" \
    "$PY" manage.py migrate --noinput
run_check "REG-04" "Full automated test suite" \
    "$PY" manage.py test --noinput
run_check "REG-05" "Performance suite (not auto-discovered; run explicitly)" \
    "$PY" manage.py test inventory.performance_test --noinput -v 2
run_check "REG-06" "Demo seed command, first run" \
    "$PY" manage.py seed_demo_data
run_check "REG-07" "Demo seed command, second run (idempotency)" \
    "$PY" manage.py seed_demo_data

# Row counts after two seed runs: the second run must not add rows.
COUNTS="$(cd "$WORK" && "$PY" manage.py shell -c '
from django.contrib.auth.models import User
from inventory.models import BloodInventory, InventoryTransaction
from donations.models import Donation
from requests.models import BloodRequest, BloodIssue
from auditlog.models import AuditLog
for name, model in [("Users", User), ("Inventory batches", BloodInventory),
                    ("Inventory transactions", InventoryTransaction),
                    ("Donations", Donation), ("Blood requests", BloodRequest),
                    ("Blood issues", BloodIssue), ("Audit log entries", AuditLog)]:
    print(f"| {name} | {model.objects.count()} |")
' 2>&1)"

{
    echo "# BBMS Regression Run — ${RUN_DATE}"
    echo
    echo "Generated by \`scripts/run_regression.sh\`. Every result below is the"
    echo "real output of the listed command, run against a clean copy of the"
    echo "committed code; nothing is estimated."
    echo
    echo "| Field | Value |"
    echo "| --- | --- |"
    echo "| Run at | ${RUN_TIME} |"
    echo "| Run by | ${RUNNER} |"
    echo "| Commit tested | \`${COMMIT}\` (branch \`${BRANCH}\`) |"
    echo "| Python | $("$PY" --version 2>&1) |"
    echo "| Django | $("$PY" -c 'import django; print(django.get_version())' 2>&1) |"
    echo "| OS | $(uname -sr) |"
    echo "| Database | SQLite (fresh, throwaway copy) |"
    echo
    echo "## Summary"
    echo
    if [ $FAILED -eq 0 ]; then
        echo "**Overall result: PASS** — every check below passed."
    else
        echo "**Overall result: FAIL** — at least one check failed; see details."
    fi
    echo
    echo "| ID | Check | Command | Result | Time |"
    echo "| --- | --- | --- | --- | --- |"
    printf "%s" "$SUMMARY_ROWS"
    echo
    echo "## Demo data row counts (after two seed runs)"
    echo
    echo "Test Plan v2.0 §6.1 expects 5 / 7 / 8 / 2 / 3 / 1 / 8; matching counts"
    echo "after the second run confirm the seed command is idempotent."
    echo
    echo "| Table | Rows |"
    echo "| --- | --- |"
    echo "$COUNTS"
    echo
    echo "## Traceability"
    echo
    echo "REG-01..03 and REG-06/07 re-verify Test Plan v2.0 §13 sign-off items;"
    echo "REG-04 is the regression run of every UT/IT/ST/SEC case marked Pass in"
    echo "BBMS_Test_Case_Catalogue.xlsx; REG-05 re-verifies BBMS-NF-001."
    echo
    echo "## Details"
    echo
    cat "$WORK/.details.md"
} > "$REPORT"

echo
echo "Report written to: ${REPORT#$REPO_ROOT/}"
exit $FAILED
